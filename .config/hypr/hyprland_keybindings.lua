local home = os.getenv("HOME") or ""
local hyprScripts = home .. "/.config/hypr/scripts"
local ml4wScripts = home .. "/.config/ml4w/scripts"

local function bind(key, dispatcher, options)
    hl.bind(key, dispatcher, options)
end

local function bindCommand(key, command, options)
    bind(key, hl.dsp.exec_cmd(command), options)
end

local function bindMain(key, dispatcher, options)
    bind("SUPER + " .. key, dispatcher, options)
end

local function bindMainCommand(key, command, options)
    bindCommand("SUPER + " .. key, command, options)
end

